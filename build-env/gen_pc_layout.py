def menu_item(name, x):
    return f"""        <TextView
            android:id="@+id/js8_menubar_{name.lower()}"
            style="@style/Js8FrameText"
            android:layout_width="wrap_content"
            android:layout_height="match_parent"
            android:layout_marginStart="{x - 8}dp"
            android:gravity="center"
            android:paddingStart="8dp"
            android:paddingEnd="8dp"
            android:text="{name}" />
"""


def button(id_, text, x, w, enabled):
    en = "" if enabled else '\n            android:enabled="false"'
    return f"""        <androidx.appcompat.widget.AppCompatButton
            android:id="@+id/{id_}"
            style="@style/Js8Button"
            android:layout_width="{w}dp"
            android:layout_marginStart="{x}dp"{en}
            android:text="{text}" />
"""


